# Generate src/stdlib_data.jl (PLAN.md D10) from the running Julia's stdlib directory and
# default sysimage. Run with exactly Julia 1.13.2:
#
#   julia --startup-file=no contrib/generate_stdlib_data.jl > src/stdlib_data.jl
#
# The output is deterministic (sorted by name) so regenerating on the same install is a no-op.

import TOML

VERSION == v"1.13.2" || error("generate with Julia 1.13.2, not $VERSION")

const STDLIB_DIR = normpath(joinpath(Sys.BINDIR, "..", "share", "julia", "stdlib", "v$(VERSION.major).$(VERSION.minor)"))

# Same lookup as `Types.load_stdlib` (projectfile_path(...; strict = true)).
function project_file(dir)
    for name in Base.project_names
        f = joinpath(dir, name)
        isfile(f) && return f
    end
    return nothing
end

str(x) = repr(x)
strvec(v) = "String[" * join(map(repr, v), ", ") * "]"
pairs_su(d) = "Pair{String, String}[" * join(["$(repr(k)) => $(repr(d[k]))" for k in sort!(collect(keys(d)))], ", ") * "]"
function pairs_exts(d)
    items = String[]
    for k in sort!(collect(keys(d)))
        v = d[k]
        push!(items, "$(repr(k)) => " * (v isa String ? repr(v) : strvec(v)))
    end
    return "Pair{String, Union{String, Vector{String}}}[" * join(items, ", ") * "]"
end

entries = String[]
for name in sort!(readdir(STDLIB_DIR))
    pf = project_file(joinpath(STDLIB_DIR, name))
    pf === nothing && continue
    p = TOML.parsefile(pf)
    uuid = get(p, "uuid", nothing)
    uuid === nothing && continue
    version = get(p, "version", nothing)
    push!(entries, string(
        "    (name = ", repr(name), ", uuid = ", repr(uuid),
        ", version = ", version === nothing ? "nothing" : repr(version), ",\n",
        "        deps = ", pairs_su(get(p, "deps", Dict{String, Any}())), ",\n",
        "        weakdeps = ", pairs_su(get(p, "weakdeps", Dict{String, Any}())), ",\n",
        "        exts = ", pairs_exts(get(p, "extensions", Dict{String, Any}())), ",\n",
        "        entryfile = ", repr(get(p, "entryfile", nothing)), "),",
    ))
end

sysimage = String[]
for id in sort!(collect(Base._sysimage_modules); by = id -> id.name)
    id.uuid === nothing && continue # Base, Core, Main
    origin = get(Base.pkgorigins, id, nothing)
    v = origin === nothing ? nothing : origin.version
    push!(sysimage, string("    (name = ", repr(id.name), ", uuid = ", repr(string(id.uuid)),
        ", version = ", v === nothing ? "nothing" : repr(string(v)), "),"))
end

print("""
# This file is a part of Julia. License is MIT: https://julialang.org/license
#
# GENERATED by contrib/generate_stdlib_data.jl from Julia $(VERSION) — do not edit.
# PkgWasm (PLAN.md D10): the stdlib universe and the default-sysimage package list are
# embedded, so no stdlib directory or sysimage is consulted at run time.

const STDLIB_DATA_JULIA_VERSION = v"$(VERSION)"

# One entry per directory of share/julia/stdlib/v$(VERSION.major).$(VERSION.minor) with a project file
# that has a uuid (the set `Types.load_stdlib` reads), in name order.
const StdlibDataEntry = @NamedTuple{
    name::String, uuid::String, version::Union{Nothing, String},
    deps::Vector{Pair{String, String}}, weakdeps::Vector{Pair{String, String}},
    exts::Vector{Pair{String, Union{String, Vector{String}}}}, entryfile::Union{Nothing, String},
}
const STDLIB_DATA = StdlibDataEntry[
$(join(entries, "\n"))
]

# Packages in the default sysimage (`Base._sysimage_modules` minus Base/Core/Main), with the
# version recorded in `Base.pkgorigins`. Replaces `Base.in_sysimage`/`Base.pkgorigins`.
const SysimagePkgEntry = @NamedTuple{name::String, uuid::String, version::Union{Nothing, String}}
const SYSIMAGE_PKGS = SysimagePkgEntry[
$(join(sysimage, "\n"))
]
""")
